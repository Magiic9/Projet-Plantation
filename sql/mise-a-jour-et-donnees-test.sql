-- ============================================================================
-- Plantation Manager : mise à jour de la base + données de test réalistes
-- ============================================================================
-- À lancer dans DBeaver sur la base "Plantation" (Alt+X = exécuter le script).
--
-- 1. Met la base au format attendu par l'application :
--    - travail.heure_debut / heure_fin : TIMESTAMP -> TIME (la date est dans la colonne "date")
--    - parcelle.surface : INTEGER -> nombre décimal
--    - nouvelles colonnes employe.photo, taux_horaire, code_pin
--    - nouvelle table pointage (arrivées / départs)
-- 2. EFFACE tous les travaux et pointages, puis en recrée pour les 4 dernières semaines :
--    du lundi au vendredi, arrivée vers 7h, pause midi, départ entre 15h et 16h30,
--    une tâche le matin et une l'après-midi, 2 départs oubliés à corriger,
--    et des employés sur place aujourd'hui (si le script est lancé en journée).
-- 3. Donne un taux horaire et le code PIN 1234 aux employés qui n'en ont pas.
--
-- Les employés, parcelles et tâches existants sont conservés.
-- Tout se fait dans une transaction : en cas d'erreur, rien n'est modifié.
-- ============================================================================

BEGIN;

-- Pour chiffrer les codes PIN au même format que l'application (BCrypt)
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ── 1. Structure ────────────────────────────────────────────────────────────

DO $$
BEGIN
    IF (SELECT data_type FROM information_schema.columns
        WHERE table_name = 'travail' AND column_name = 'heure_debut') <> 'time without time zone' THEN
        ALTER TABLE travail
            ALTER COLUMN heure_debut TYPE time(0) USING heure_debut::time(0),
            ALTER COLUMN heure_fin   TYPE time(0) USING heure_fin::time(0);
    END IF;
END $$;

ALTER TABLE parcelle ALTER COLUMN surface TYPE double precision;

ALTER TABLE employe ADD COLUMN IF NOT EXISTS photo        varchar(255);
ALTER TABLE employe ADD COLUMN IF NOT EXISTS taux_horaire double precision;
ALTER TABLE employe ADD COLUMN IF NOT EXISTS code_pin     varchar(255);

CREATE TABLE IF NOT EXISTS pointage (
    pointage_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employe_id    integer NOT NULL REFERENCES employe (employe_id),
    date          date    NOT NULL,
    heure_arrivee time(0) NOT NULL,
    heure_depart  time(0)
);

-- ── 2. Employés : taux horaire et code PIN de test ─────────────────────────

UPDATE employe
SET taux_horaire = COALESCE(taux_horaire, round((11.88 + random() * 1.62)::numeric, 2)),
    code_pin     = COALESCE(code_pin, crypt('1234', gen_salt('bf', 10)))
WHERE actif;

-- ── 3. On repart de zéro pour les travaux et pointages ─────────────────────

TRUNCATE travail, pointage RESTART IDENTITY;

-- Une ligne par employé et par jour travaillé (92 % de présence)
CREATE TEMP TABLE jours ON COMMIT DROP AS
SELECT e.employe_id,
       d::date                                                        AS jour,
       time '06:45' + (floor(random() * 45) || ' minutes')::interval  AS arrivee,
       time '11:30' + (floor(random() * 30) || ' minutes')::interval  AS pause_debut,
       time '12:45' + (floor(random() * 30) || ' minutes')::interval  AS pause_fin,
       time '15:00' + (floor(random() * 90) || ' minutes')::interval  AS depart
FROM employe e
CROSS JOIN generate_series(CURRENT_DATE - 28, CURRENT_DATE - 1, interval '1 day') AS d
WHERE e.actif
  AND extract(isodow FROM d) <= 5
  AND random() < 0.92;

-- Pointages : matin et après-midi
INSERT INTO pointage (employe_id, date, heure_arrivee, heure_depart)
SELECT employe_id, jour, arrivee, pause_debut FROM jours
UNION ALL
SELECT employe_id, jour, pause_fin, depart FROM jours;

-- Travaux : une tâche le matin, une l'après-midi, tâche et parcelle au hasard
WITH t AS (SELECT array_agg(tache_id) AS ids FROM tache WHERE actif),
     p AS (SELECT array_agg(parcelle_id) AS ids FROM parcelle WHERE actif)
INSERT INTO travail (employe_id, tache_id, parcelle_id, date, heure_debut, heure_fin)
SELECT j.employe_id,
       t.ids[1 + floor(random() * array_length(t.ids, 1))::int],
       p.ids[1 + floor(random() * array_length(p.ids, 1))::int],
       j.jour, j.arrivee + interval '5 minutes', j.pause_debut
FROM jours j, t, p
UNION ALL
SELECT j.employe_id,
       t.ids[1 + floor(random() * array_length(t.ids, 1))::int],
       p.ids[1 + floor(random() * array_length(p.ids, 1))::int],
       j.jour, j.pause_fin + interval '5 minutes', j.depart - interval '5 minutes'
FROM jours j, t, p;

-- 2 départs oubliés la semaine dernière (à corriger dans l'onglet Pointages)
UPDATE pointage SET heure_depart = NULL
WHERE pointage_id IN (
    SELECT pointage_id FROM pointage
    WHERE date >= CURRENT_DATE - 7 AND heure_arrivee > time '12:00'
    ORDER BY random() LIMIT 2);

-- Aujourd'hui (jour de semaine, après 7h30) : 75 % des employés sur place, tâche en cours
INSERT INTO pointage (employe_id, date, heure_arrivee)
SELECT employe_id, CURRENT_DATE,
       LEAST(time '06:50' + (floor(random() * 40) || ' minutes')::interval, LOCALTIME(0) - interval '10 minutes')
FROM employe
WHERE actif
  AND random() < 0.75
  AND LOCALTIME > time '07:30'
  AND extract(isodow FROM CURRENT_DATE) <= 5;

WITH t AS (SELECT array_agg(tache_id) AS ids FROM tache WHERE actif),
     p AS (SELECT array_agg(parcelle_id) AS ids FROM parcelle WHERE actif)
INSERT INTO travail (employe_id, tache_id, parcelle_id, date, heure_debut, heure_fin)
SELECT po.employe_id,
       t.ids[1 + floor(random() * array_length(t.ids, 1))::int],
       p.ids[1 + floor(random() * array_length(p.ids, 1))::int],
       CURRENT_DATE, po.heure_arrivee + interval '5 minutes', NULL
FROM pointage po, t, p
WHERE po.date = CURRENT_DATE;

COMMIT;

-- ── Vérification ────────────────────────────────────────────────────────────

SELECT 'employés actifs'           AS quoi, count(*) AS nombre FROM employe  WHERE actif
UNION ALL SELECT 'pointages',                count(*) FROM pointage
UNION ALL SELECT 'travaux',                  count(*) FROM travail
UNION ALL SELECT 'départs oubliés',          count(*) FROM pointage WHERE heure_depart IS NULL AND date < CURRENT_DATE
UNION ALL SELECT 'sur place aujourd''hui',   count(*) FROM pointage WHERE date = CURRENT_DATE AND heure_depart IS NULL
UNION ALL SELECT 'travaux incohérents (doit être 0)', count(*) FROM travail WHERE heure_fin <= heure_debut;
